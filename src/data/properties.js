let _livePropertiesCache = [...sampleProperties];

export function setLivePropertiesCache(props) {
  if (Array.isArray(props)) {
    _livePropertiesCache = props;
  }
}

export function getAllProperties() {
  return _livePropertiesCache;
}

export function getPropertyBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = String(slug).toLowerCase().trim();
  return (
    _livePropertiesCache.find(
      (p) =>
        (p.slug && p.slug.toLowerCase() === cleanSlug) ||
        (p.id && p.id.toLowerCase() === cleanSlug)
    ) || null
  );
}

export function getSimilarProperties(property, limit = 3) {
  if (!property) return [];
  return _livePropertiesCache
    .filter(
      (p) =>
        p.id !== property.id &&
        (p.locality === property.locality ||
          p.category === property.category ||
          p.transactionType === property.transactionType)
    )
    .slice(0, limit);
}

