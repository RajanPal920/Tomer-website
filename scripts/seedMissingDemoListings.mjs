export async function seedMissingDemoListings() {
  console.log(`\n=== TOMAR ENTERPRISES IDEMPOTENT DEMO SEEDER ===`);
  console.log(`Checking ${MISSING_DEMO_SPECS.length} required demo listings...`);

  const now = new Date().toISOString();
  let dbInserted = 0;
  let dbUpdated = 0;

  for (const spec of MISSING_DEMO_SPECS) {
    const existing = await get('SELECT id, is_demo FROM properties WHERE id = ?', [spec.id]);

    const image = spec.image || getNextImage();
    const gallery = [image, getNextImage()];
    const slug = `${spec.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)+/g, '')}-${spec.locality}`;

    if (!existing) {
      await run(`
        INSERT INTO properties (
          id, slug, title, category, transaction_type, locality, sub_location, address,
          price, price_display, price_per_sqft, price_number, monthly_rent, deposit_amount,
          lease_term, area_sqft, area_display, area_unit, bedrooms, bathrooms, furnishing,
          possession_status, image, gallery, features, description, status, featured,
          is_demo, is_verified, internal_notes, created_at, updated_at
        ) VALUES (
          ?, ?, ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?
        )
      `, [
        spec.id,
        slug,
        spec.title,
        spec.category,
        spec.transactionType,
        spec.locality,
        spec.subLocation,
        `${spec.subLocation}, Palghar District, Maharashtra`,
        spec.price,
        spec.priceDisplay,
        spec.pricePerSqft || null,
        spec.priceNumber || null,
        spec.monthlyRent || null,
        spec.depositAmount || null,
        spec.leaseTerm || null,
        spec.areaSqFt || null,
        spec.areaDisplay || null,
        spec.areaUnit || 'sq.ft',
        spec.bedrooms !== undefined ? spec.bedrooms : null,
        spec.bathrooms !== undefined ? spec.bathrooms : null,
        spec.furnishing || 'Unfurnished',
        spec.possessionStatus || 'Ready to Move',
        image,
        JSON.stringify(gallery),
        JSON.stringify(spec.features || []),
        spec.description,
        'published', // Published so public search can display them
        0, // featured = 0
        1, // is_demo = 1 (clearly marked demo)
        0, // is_verified = 0 (unverified sample inventory)
        'Sample demonstration inventory created to ensure complete corridor coverage for prospective buyers and tenants. Not a genuine owner mandate.',
        now,
        now,
      ]);
      dbInserted++;
    } else {
      // If already present, make sure it is published and is_demo = 1
      await run(`
        UPDATE properties
        SET status = 'published', is_demo = 1, is_verified = 0, updated_at = ?
        WHERE id = ? AND is_demo = 1
      `, [now, spec.id]);
      dbUpdated++;
    }
  }

  console.log(`Database sync: ${dbInserted} new inserted, ${dbUpdated} verified/updated.`);

  // Now synchronize src/data/properties.js sampleProperties array
  console.log(`Synchronizing src/data/properties.js...`);
  const existingJsContent = fs.readFileSync(PROPERTIES_JS_PATH, 'utf-8');

  // Build complete list of new properties to append if not already in sampleProperties
  const existingIdMatches = existingJsContent.match(/"id":\s*"([^"]+)"/g) || [];
  const existingIds = new Set(existingIdMatches.map((m) => m.match(/"id":\s*"([^"]+)"/)[1]));
  const newPropertiesForJs = [];

  for (const spec of MISSING_DEMO_SPECS) {
    if (!existingIds.has(spec.id)) {
      const image = spec.image || getNextImage();
      const gallery = [image, getNextImage()];
      const slug = `${spec.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)+/g, '')}-${spec.locality}`;

      newPropertiesForJs.push({
        id: spec.id,
        slug,
        title: spec.title,
        category: spec.category,
        transactionType: spec.transactionType,
        locality: spec.locality,
        subLocation: spec.subLocation,
        address: `${spec.subLocation}, Palghar District, Maharashtra`,
        price: spec.priceNumber || spec.price,
        priceDisplay: spec.priceDisplay,
        pricePerSqft: spec.pricePerSqft || null,
        priceNumber: spec.priceNumber || null,
        monthlyRent: spec.monthlyRent || null,
        depositAmount: spec.depositAmount || null,
        leaseTerm: spec.leaseTerm || null,
        areaSqFt: spec.areaSqFt || null,
        areaDisplay: spec.areaDisplay || null,
        areaUnit: spec.areaUnit || 'sq.ft',
        bedrooms: spec.bedrooms !== undefined ? spec.bedrooms : null,
        bathrooms: spec.bathrooms !== undefined ? spec.bathrooms : null,
        furnishing: spec.furnishing || 'Unfurnished',
        possessionStatus: spec.possessionStatus || 'Ready to Move',
        possessionDisplay: spec.possessionDisplay || spec.possessionStatus || 'Ready to Move',
        image,
        gallery,
        features: spec.features || [],
        description: spec.description,
        status: 'published',
        featured: false,
        isDemo: true,
        isVerified: false,
        internalNotes: 'Sample demonstration inventory created to ensure complete corridor coverage for prospective buyers and tenants. Not a genuine owner mandate.',
      });
    }
  }

  if (newPropertiesForJs.length > 0) {
    console.log(`Adding ${newPropertiesForJs.length} properties to sampleProperties in properties.js...`);

    const marker = '\n];\n\nlet _livePropertiesCache = [...sampleProperties];';
    if (existingJsContent.includes(marker)) {
      const formattedNewProps = newPropertiesForJs.map((p) => '  ' + JSON.stringify(p, null, 2).replace(/\n/g, '\n  ')).join(',\n');
      const updatedJs = existingJsContent.replace(marker, ',\n' + formattedNewProps + marker);
      fs.writeFileSync(PROPERTIES_JS_PATH, updatedJs, 'utf-8');
      console.log(`Successfully updated ${PROPERTIES_JS_PATH} with ${newPropertiesForJs.length} properties.`);
    } else {
      console.error('Could not find exact closing marker for sampleProperties in properties.js');
    }
  } else {
    console.log(`All ${MISSING_DEMO_SPECS.length} demo properties are already present in properties.js.`);
  }

  console.log(`=== DEMO SEEDING COMPLETE ===\n`);
}

// Allow direct CLI execution
if (process.argv[1] && process.argv[1].endsWith('seedMissingDemoListings.mjs')) {
  seedMissingDemoListings()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('Error during demo seeding:', err);
      process.exit(1);
    });
}
